"""
Serializers for AI Learning Assistant API.
Implements robust input validation and bounded parameter checks for Stage 15.
"""
from django.conf import settings
from rest_framework import serializers

DEFAULT_MAX_MESSAGE_CHARS = getattr(settings, "AI_MAX_MESSAGE_CHARS", 2000)


class AIAssistantAskRequestSerializer(serializers.Serializer):
    """
    Validates student inquiry requests to the AI Learning Assistant.
    Enforces non-empty, non-whitespace-only, and bounded length messages.
    """
    lesson_id = serializers.IntegerField(
        required=True,
        min_value=1,
        help_text="Primary key of the lesson context.",
        error_messages={
            "required": "A valid lesson_id is required.",
            "invalid": "lesson_id must be a valid integer.",
            "min_value": "lesson_id must be a positive integer.",
        },
    )
    message = serializers.CharField(
        required=True,
        min_length=1,
        max_length=DEFAULT_MAX_MESSAGE_CHARS,
        trim_whitespace=True,
        help_text="The question or prompt submitted by the student.",
        error_messages={
            "required": "Message cannot be empty.",
            "blank": "Message cannot be empty.",
            "max_length": f"Message cannot exceed {DEFAULT_MAX_MESSAGE_CHARS} characters.",
        },
    )

    def validate_message(self, value):
        cleaned = value.strip()
        if not cleaned:
            raise serializers.ValidationError(
                "Question cannot be empty or whitespace only."
            )
        return cleaned


class AIAssistantAskResponseSerializer(serializers.Serializer):
    """
    Serializes AI Learning Assistant responses with bounded output size.
    """
    answer = serializers.CharField(
        help_text="The response generated by the AI tutor.",
    )
    lesson_id = serializers.IntegerField(
        help_text="The lesson context identifier.",
    )
